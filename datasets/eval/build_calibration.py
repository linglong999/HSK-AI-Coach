def build():
    items = []
    bad = []
    for (dim, quality), texts in _SAMPLES.items():
        for t in texts:
            if len(t.strip()) < 4:
                bad.append((dim, quality, t))
            items.append({"id": f"CAL-{len(items)+1:03d}", "dim": dim,
                          "quality": quality, "gold_pass": quality == "high",
                          "text": t})
    if bad:
        for b in bad:
            print("skip empty:", b)
    items = items[:100]

    os.makedirs(_CAL, exist_ok=True)
    dist_q = dict(Counter(x["quality"] for x in items))
    dist_d = dict(Counter(x["dim"] for x in items))
    meta = {
        "name": "hsk_calibration_100", "version": "b6-cal-v1", "date": "2026-09-24",
        "n": len(items),
        "note": "自包含教学回复文本（judge∧人工同对象）；rubric.md v2 双门槛；"
                "gold_pass 仅口径提示，最终以 judge∧人工 kappa 为准",
        "dist_quality": dist_q, "dist_dim": dist_d,
    }
    with open(os.path.join(_CAL, "calibration_cases.json"), "w", encoding="utf-8") as f:
        json.dump({"meta": meta, "cases": items}, f, ensure_ascii=False, indent=2)

    with open(os.path.join(_CAL, "annotation_template.csv"), "w", encoding="utf-8-sig",
              newline="") as f:
        w = csv.writer(f)
        w.writerow(["id", "focus_dim", "quality_ref", "gold_pass_ref", "text", "verdict",
                    "d1", "d2", "d3", "d4", "d5", "d6", "d7", "d8", "d9", "d10", "reason"])
        for x in items:
            w.writerow([x["id"], x["dim"], x["quality"], x["gold_pass"], x["text"],
                        "", "", "", "", "", "", "", "", "", "", "", ""])
    print(f"wrote {len(items)} cases -> calibration_cases.json / annotation_template.csv")
    print("quality", dist_q)
    print("dim", dist_d)


if __name__ == "__main__":
    build()