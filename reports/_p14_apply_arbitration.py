LIMITS = {V1: (1, 15), V2: (1, 15), V3: (1, 20), V4A: (1, 10), V4B: (11, 20)}
out = []
for r in rows:
    v, l, note = D[r["hsk_id"]]
    assert (v == "") == (l == ""), f"{r['hsk_id']} volume/lesson 不成对: {v!r}/{l!r}"
    if v:
        lo, hi = LIMITS[v]
        assert lo <= int(l) <= hi, f"{r['hsk_id']} 课次越界: {v}·{l}"
    if v == "" and l == "":
        miss += 1
    elif (v, l) != (r["volume"], r["lesson"]):
        changed += 1
    else:
        kept += 1
    if note.startswith(NEAR):
        near += 1
